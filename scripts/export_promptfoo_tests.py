"""Exports data/golden.jsonl to promptfoo/tests.yaml so promptfoo and evalkit share one dataset."""

from pathlib import Path

import yaml

from evalkit.dataset import load_cases

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    tests = []
    for c in load_cases(ROOT / "data/golden.jsonl"):
        test_vars = {"case_id": c.id, "question": c.question, "workspace": c.workspace,
                     "reference": c.reference_answer or "", "expect_refusal": c.expect_refusal}
        for key in ("must_include_any", "must_include_all", "must_not_include"):
            if getattr(c, key):
                test_vars[key] = getattr(c, key)
        tests.append({"description": f"{c.id} [{', '.join(c.tags)}] {c.question}", "vars": test_vars})
    out = ROOT / "promptfoo/tests.yaml"
    out.write_text("# Generated by scripts/export_promptfoo_tests.py from data/golden.jsonl. Do not edit by hand.\n"
                   + yaml.safe_dump(tests, allow_unicode=True, sort_keys=False, width=120), encoding="utf-8")
    print(f"saved {len(tests)} tests to {out}")


if __name__ == "__main__":
    main()
